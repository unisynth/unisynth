"""Filter test vectors for unisynth's cauldron slot, from the bit-exact reference code.

Runs the oscillator at a constant pitch (gain 1) through the original resonant filter, retriggering once at
`restart` (phase -32766, prev 0, v1 = A2, v2 = B2; the filter's y runs on), and prints the filter output per frame:
    python3 tools/filter_vectors.py > crates/unisynth/src/osc/cauldron_filter_vectors.rs
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ref'))
import mcauldron1 as m1, mcauldron2 as m2

def run(version, wave, voices, pitch, a, b, decay, damp, n, restart, a2, b2):
    m = m1 if version == 1 else m2
    syn = m.Synth.__new__(m.Synth); syn.t = 0; syn.seg_reg = 1; syn.buf = bytearray(1 << 17)
    # one untied step, so frame() takes no glide; no fade (frame() fades and clamps after the filter: we read prev)
    P = {'voices': voices, 'wave': wave, 'gain': 1.0, 'pitch': [pitch] * 16, 'tie': [0] * 17, 'hold': 0x7FFF, 'release': 0, 'after_tie': 0}
    st = dict(phase=-32766, phase2=0, v1=a, v2=b, q=damp, d=decay, y=0.0, prev=0, pitch=pitch)
    out = []
    for i in range(n):
        if i == restart:
            st.update(phase=-32766, prev=0, v1=a2, v2=b2)
        syn.frame(P, st, 0)
        out.append(st['prev'])
    return out

CASES = [  # name, version, wave, voices, pitch, A, B, decay, damp, frames, restart, A2, B2
    ('V1_SAW_RETRIGGER', 1, 0, 0, 199, 0.08, 0.04, 0.999, 0.1, 3000, 1500, 0.1, 0.05),
    ('V1_RESONANT_PAIR', 1, 0, 2, 211, 0.002, 0.001, 0.9998, 0.001, 3000, 2000, 0.0022, 0.0011),
    ('V1_SPIKE', 1, 2, 3, 199, 0.2, 0.01, 0.998, 0.05, 2000, 1000, 0.8, 0.04),
    ('V2_RISING', 2, 0, 0, 800, 0.0064, 0.0001, 1.0001, 0.05, 6000, 4000, 0.007, 0.00011),
    ('V2_SQUARE_BRIGHT', 2, 1, 1, 847, 4.699349880218506, 0.009178457781672478, 1.0000100135803223, 0.800000011920929, 2000, 1000, 4.2, 0.0082),  # BLUISH record 9
]
print('// Generated by research/tbl-mini-cauldron/tools/filter_vectors.py from the bit-exact references; do not edit.')
print('// (name, version, wave, voices, pitch, A, B, decay, damp, restart, A2, B2, filter output per frame)')
print('pub const CASES: &[(&str, u8, u8, u8, u32, f64, f64, f64, f64, usize, f64, f64, &[i32])] = &[')
for name, v, w, vo, p, a, b, d, q, n, r, a2, b2 in CASES:
    vals = run(v, w, vo, p, a, b, d, q, n, r, a2, b2)
    print(f'    ("{name}", {v}, {w}, {vo}, {p}, {a!r}, {b!r}, {d!r}, {q!r}, {r}, {a2!r}, {b2!r}, &[{", ".join(map(str, vals))}]),')
print('];')
