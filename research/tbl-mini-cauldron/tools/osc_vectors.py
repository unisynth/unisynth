"""Oscillator-only test vectors for unisynth's cauldron slot, from the bit-exact reference code.

Runs the oscillator part of the v1/v2 frame (before the gain and the filter) at a constant pitch from the
retrigger phase -32766, with the phrase frame counter starting at t0, and prints Rust test tables:
    python3 tools/osc_vectors.py > crates/unisynth/src/osc/cauldron_vectors.rs
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ref'))
import mcauldron1 as m1, mcauldron2 as m2

def run(version, wave, voices, pitch, t0, n):
    st = {'phase': -32766, 'phase2': 0, 'pitch': pitch}
    out = []
    if version == 1:
        s = m1.Synth.__new__(m1.Synth); s.t = t0
        P = {'voices': voices, 'wave': wave}
        for _ in range(n):
            o = st['phase']
            if voices != 0:
                st['phase2'] = m1.i16(st['phase2'] + m1.fistp(m1.mul(float(m1.s32(st['pitch'])), m1.DETUNE)))
                o += st['phase2']
            if wave == 2:
                k = 0
                while True:
                    o = m1.fistp(m1.shape7(st['phase']))
                    if voices != 0:
                        off = (((s.t * k) & 0xFFFFFFFF) * (st['pitch'] & 0xFFFFFFFF) >> 7) & 0xFFFFFFFF
                        if not (k & 1):
                            off = (-off) & 0xFFFFFFFF
                        st['phase2'] = m1.i16(st['phase'] + off)
                        o = m1.fistp(m1.add(m1.shape7(st['phase2']), float(o)))
                    k += 1
                    if k > voices:
                        break
            out.append(o)
            st['phase'] = m1.i16(st['phase'] + st['pitch'])
            s.t += 1
    else:
        s = m2.Synth.__new__(m2.Synth); s.t = t0
        P = {'voices': voices, 'wave': wave}
        for _ in range(n):
            o = st['phase']
            if voices != 0:
                st['phase2'] = m2.i16(st['phase2'] + m2.fistp(m2.mul(float(m2.s32(st['pitch'])), m2.DETUNE)))
                o += st['phase2']
            if wave == 1:
                o = 30000 if o > 0 else -30000
            elif wave == 2:
                o = s.wave2(P, st)
            elif wave == 3:
                o = 30000 if o > 31000 else 0
            elif wave == 5:
                if o > 0:
                    o = 0x7FFF - o
            out.append(m2.clamp16(o))
            st['phase'] = m2.i16(st['phase'] + st['pitch'])
            s.t += 1
    return out

CASES = [  # name, version, wave, voices, pitch, t0, frames
    ('V1_SAW', 1, 0, 0, 799, 0, 400),
    ('V1_SAW_PAIR', 1, 0, 2, 199, 0, 400),
    ('V1_SPIKE3', 1, 2, 3, 199, 0, 400),
    ('V1_SPIKE2_LATE', 1, 2, 2, 251, 30000, 400),
    ('V2_SQUARE_PAIR', 2, 1, 1, 211, 0, 400),
    ('V2_SPIKE', 2, 2, 0, 399, 0, 400),
    ('V2_SPIKE10_WRAP', 2, 2, 10, 199, 6400, 400),
    ('V2_PULSE_PAIR', 2, 3, 5, 237, 0, 400),
    ('V2_FOLD', 2, 5, 0, 423, 0, 400),
]
print('// Generated by research/tbl-mini-cauldron/tools/osc_vectors.py from the bit-exact references; do not edit.')
print('// (name, version, wave, voices, pitch, t0, oscillator output before gain per frame)')
print('pub const CASES: &[(&str, u8, u8, u8, u32, u32, &[i32])] = &[')
for name, v, w, vo, p, t0, n in CASES:
    vals = run(v, w, vo, p, t0, n)
    print(f'    ("{name}", {v}, {w}, {vo}, {p}, {t0}, &[{", ".join(map(str, vals))}]),')
print('];')
